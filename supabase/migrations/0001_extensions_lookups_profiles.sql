-- ---------------------------------------------------------------------------
-- Profiles
-- ---------------------------------------------------------------------------
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'creator' check (role in ('creator','brand','admin')),
  username extensions.citext not null unique
    check (username::text ~ '^[a-z0-9_.]{3,30}$'),
  display_name text not null check (char_length(display_name) between 1 and 80),
  avatar_url text,
  cover_url text,
  headline text check (char_length(headline) <= 140),
  bio text check (char_length(bio) <= 1200),
  location text check (char_length(location) <= 80),
  website text check (char_length(website) <= 200),
  links jsonb not null default '{}'::jsonb check (jsonb_typeof(links) = 'object'),
  is_verified boolean not null default false,
  is_suspended boolean not null default false,
  onboarded boolean not null default false,
  search tsvector generated always as (
    to_tsvector('simple',
      coalesce(username::text, '') || ' ' || coalesce(display_name, '') || ' ' ||
      coalesce(headline, '') || ' ' || coalesce(bio, '') || ' ' || coalesce(location, ''))
  ) stored,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index profiles_role_idx on public.profiles(role) where not is_suspended;
create index profiles_created_idx on public.profiles(created_at desc);
create index profiles_search_idx on public.profiles using gin(search);
create index profiles_display_name_trgm on public.profiles using gin(display_name extensions.gin_trgm_ops);
create index profiles_username_trgm on public.profiles using gin((username::text) extensions.gin_trgm_ops);

-- Counters live in their own table: clients can read but never write them.
create table public.profile_stats (
  profile_id uuid primary key references public.profiles(id) on delete cascade,
  followers_count int not null default 0 check (followers_count >= 0),
  following_count int not null default 0 check (following_count >= 0),
  posts_count int not null default 0 check (posts_count >= 0),
  likes_received_count int not null default 0 check (likes_received_count >= 0),
  updated_at timestamptz not null default now()
);
create index profile_stats_followers_idx on public.profile_stats(followers_count desc);

create table public.creator_details (
  profile_id uuid primary key references public.profiles(id) on delete cascade,
  experience_level text not null default 'emerging'
    check (experience_level in ('emerging','intermediate','professional','expert')),
  availability text not null default 'open' check (availability in ('open','limited','booked')),
  years_experience smallint check (years_experience between 0 and 60),
  rate_min int check (rate_min >= 0),
  rate_max int check (rate_max >= 0),
  currency text not null default 'USD' check (char_length(currency) = 3),
  workflow_overview text check (char_length(workflow_overview) <= 2000),
  updated_at timestamptz not null default now(),
  check (rate_max is null or rate_min is null or rate_max >= rate_min)
);
create index creator_details_exp_idx on public.creator_details(experience_level);
create index creator_details_avail_idx on public.creator_details(availability);

create table public.brand_details (
  profile_id uuid primary key references public.profiles(id) on delete cascade,
  company_name text not null check (char_length(company_name) between 1 and 120),
  industry text check (char_length(industry) <= 80),
  company_size text check (company_size in ('1-10','11-50','51-200','201-1000','1000+')),
  description text check (char_length(description) <= 2000),
  updated_at timestamptz not null default now()
);

-- Past brand / campaign experience shown on creator profiles
create table public.creator_experiences (
  id uuid primary key default gen_random_uuid(),
  creator_id uuid not null references public.profiles(id) on delete cascade,
  brand_name text not null check (char_length(brand_name) between 1 and 120),
  project_title text not null check (char_length(project_title) between 1 and 160),
  year smallint check (year between 1990 and 2100),
  description text check (char_length(description) <= 1000),
  link text check (char_length(link) <= 500),
  created_at timestamptz not null default now()
);
create index creator_experiences_creator_idx on public.creator_experiences(creator_id);

