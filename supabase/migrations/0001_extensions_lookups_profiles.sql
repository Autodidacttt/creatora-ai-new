-- 0001: extensions, lookup vocabularies, profiles and role-specific details

create extension if not exists citext with schema extensions;
create extension if not exists pg_trgm with schema extensions;
create extension if not exists pgcrypto with schema extensions;

-- ---------------------------------------------------------------------------
-- Lookup tables (static vocabulary that drives every filter in the UI)
-- ---------------------------------------------------------------------------
create table public.skills (
  id int generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  sort int not null default 0
);

create table public.ai_tools (
  id int generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  category text not null check (category in ('image','video','audio','3d','llm','editing','avatar')),
  vendor text,
  sort int not null default 0
);

create table public.categories (
  id int generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  description text,
  sort int not null default 0
);

create table public.content_types (
  id int generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  sort int not null default 0
);

create table public.styles (
  id int generated by default as identity primary key,
