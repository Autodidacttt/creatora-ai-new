// Generates src/types/database.ts (supabase-js `Database` type) by introspecting Postgres.
// Usage: npm run db:types   (uses SUPABASE_DB_URL; no Supabase CLI / Docker required)
import fs from "node:fs";
import path from "node:path";
import { Client } from "pg";
import { requireEnv } from "./env";

const SCALAR: Record<string, string> = {
  uuid: "string", text: "string", citext: "string", varchar: "string", bpchar: "string",
  date: "string", timestamptz: "string", timestamp: "string", time: "string", interval: "string",
  int2: "number", int4: "number", int8: "number", float4: "number", float8: "number", numeric: "number",
  bool: "boolean", json: "Json", jsonb: "Json", tsvector: "string", void: "undefined", record: "Json",
};
const tsType = (udt: string): string => {
  if (udt.startsWith("_")) return `${tsType(udt.slice(1))}[]`;
  return SCALAR[udt] ?? "unknown";
};
const key = (name: string) => (/^[a-z_][a-z0-9_]*$/.test(name) ? name : JSON.stringify(name));

async function main() {
  const local = process.env.TYPES_DB_URL;
  const client = new Client({
    connectionString: local ?? requireEnv("SUPABASE_DB_URL"),
    ssl: local ? undefined : { rejectUnauthorized: false },
  });
  await client.connect();

  const cols = (await client.query(`
    select c.table_name, c.column_name, c.udt_name, c.is_nullable = 'YES' as nullable,
           (c.column_default is not null or c.is_identity = 'YES') as has_default,
           c.is_generated = 'ALWAYS' or c.identity_generation = 'ALWAYS' as generated,
           t.table_type
    from information_schema.columns c
    join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
    where c.table_schema = 'public'
    order by c.table_name, c.ordinal_position`)).rows as {
      table_name: string; column_name: string; udt_name: string; nullable: boolean;
      has_default: boolean; generated: boolean; table_type: string;
    }[];

  const fns = (await client.query(`
    select p.proname,
           coalesce(p.proargnames, '{}')::text[] as argnames,
           coalesce(p.proargmodes::text[], '{}') as argmodes,
           array(select t.typname from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality a(oid, n)
                 join pg_type t on t.oid = a.oid order by a.n)::text[] as argtypes,
           p.pronargdefaults, p.pronargs, p.proretset, rt.typname as rettype
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    join pg_type rt on rt.oid = p.prorettype
    where n.nspname = 'public' and p.prokind = 'f'
      and rt.typname <> 'trigger'
      and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
    order by p.proname`)).rows as {
      proname: string; argnames: string[]; argmodes: string[]; argtypes: string[];
      pronargdefaults: number; pronargs: number; proretset: boolean; rettype: string;
    }[];
  await client.end();

  const tables = new Map<string, typeof cols>();
  for (const c of cols) {
    if (!tables.has(c.table_name)) tables.set(c.table_name, []);
    tables.get(c.table_name)!.push(c);
  }

  const out: string[] = [];
  out.push("// AUTO-GENERATED by `npm run db:types`. Do not edit by hand.");
  out.push("export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];");
  out.push("");
  out.push("export type Database = {");
  out.push('  __InternalSupabase: { PostgrestVersion: "13" };');
  out.push("  public: {");

  const section = (kind: "BASE TABLE" | "VIEW") => {
    for (const [name, columns] of tables) {
      if (columns[0].table_type !== kind) continue;
      const row = columns.map((c) => `${key(c.column_name)}: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""}`);
      const writable = columns.filter((c) => !c.generated);
      const ins = writable.map((c) =>
        `${key(c.column_name)}${c.nullable || c.has_default ? "?" : ""}: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""}`);
      const upd = writable.map((c) => `${key(c.column_name)}?: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""}`);
      out.push(`      ${name}: {`);
      out.push(`        Row: { ${row.join("; ")} };`);
      if (kind === "BASE TABLE") {
        out.push(`        Insert: { ${ins.join("; ")} };`);
        out.push(`        Update: { ${upd.join("; ")} };`);
      }
      out.push("        Relationships: [];");
      out.push("      };");
    }
  };

  out.push("    Tables: {");
  section("BASE TABLE");
  out.push("    };");
  out.push("    Views: {");
  section("VIEW");
  out.push("    };");
  out.push("    Functions: {");
  // Overloaded functions (same name, different arguments) become a union, as supabase-js expects
  const signatures = new Map<string, string[]>();
  for (const f of fns) {
    const inArgs: string[] = [];
    const outCols: string[] = [];
    const firstDefault = f.pronargs - f.pronargdefaults;
    let inIdx = 0;
    f.argtypes.forEach((t, i) => {
      const mode = f.argmodes[i] ?? "i";
      const name = f.argnames[i] || `arg${i}`;
      if (mode === "i" || mode === "b") {
        inArgs.push(`${key(name)}${inIdx >= firstDefault ? "?" : ""}: ${tsType(t)}${inIdx >= firstDefault ? " | null" : ""}`);
        inIdx++;
      }
      if (mode === "t" || mode === "o" || mode === "b") outCols.push(`${key(name)}: ${tsType(t)}`);
    });
    const ret = outCols.length
      ? `{ ${outCols.join("; ")} }[]`
      : `${tsType(f.rettype)}${f.proretset ? "[]" : ""}`;
    const sig = `{ Args: ${inArgs.length ? `{ ${inArgs.join("; ")} }` : "Record<PropertyKey, never>"}; Returns: ${ret} }`;
    signatures.set(f.proname, [...(signatures.get(f.proname) ?? []), sig]);
  }
  for (const [name, sigs] of signatures) out.push(`      ${name}: ${sigs.join(" | ")};`);
  out.push("    };");
  out.push("    Enums: { [_ in never]: never };");
  out.push("    CompositeTypes: { [_ in never]: never };");
  out.push("  };");
  out.push("};");
  out.push("");
  out.push('type PublicSchema = Database["public"];');
  out.push('export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];');
  out.push('export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];');
  out.push('export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];');
  out.push("");

  const target = path.resolve(__dirname, "..", "..", "src", "types", "database.ts");
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, out.join("\n"));
  console.log(`Wrote ${path.relative(process.cwd(), target)} (${tables.size} relations, ${fns.length} functions)`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
